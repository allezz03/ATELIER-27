-- Esegui questo SQL nel SQL Editor del progetto Supabase.
create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  project text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.contact_requests enable row level security;

-- Consente agli utenti anonimi di inviare richieste dal sito.
-- Non consente lettura, modifica o cancellazione pubblica.
create policy "Anyone can submit a contact request"
on public.contact_requests
for insert
to anon
with check (
  char_length(name) > 0
  and char_length(email) > 3
  and char_length(message) > 0
);
